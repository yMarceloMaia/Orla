#!/usr/bin/env bash
set -euo pipefail
root=$(cd -- "$(dirname -- "$0")" && pwd -P)
for tool in python3 quickshell qs hyprctl omarchy systemctl zenity gio; do
  command -v "$tool" >/dev/null || { echo "Required command: $tool" >&2; exit 1; }
done
python3 -c 'from gi.repository import GioUnix' || { echo "Install python-gobject to enable recent documents." >&2; exit 1; }
sources=(orla orla.service orla-toggle.desktop)
targets=("$HOME/.local/bin/orla" "$HOME/.config/systemd/user/orla.service" "$HOME/.local/share/applications/orla-toggle.desktop")
for i in "${!targets[@]}"; do
  path=${targets[i]}
  if [[ -e $path || -L $path ]]; then
    [[ $path -ef "$root/${sources[i]}" ]] && continue
    # Launcher generated by early Orla installations.
    if [[ $i == 2 && ! -L $path ]]; then
      generated=$(sed "s|^Exec=.*|Exec=$HOME/.local/bin/orla toggle|" "$root/orla-toggle.desktop")
      if cmp -s "$path" <(printf '%s\n' "$generated") ||
         cmp -s "$path" <(printf '%s\n' "${generated/Toggle dock/Ativar ou desativar dock}"); then
        continue
      fi
    fi
    echo "A file already exists at $path. Installation stopped." >&2
    exit 1
  fi
done
for i in "${!targets[@]}"; do
  path=${targets[i]}
  mkdir -p -- "$(dirname -- "$path")"
  [[ -e $path ]] || ln -s -- "$root/${sources[i]}" "$path"
done
systemctl --user daemon-reload
echo 'Installed. To start Orla and enable it at login, run ~/.local/bin/orla enable'
